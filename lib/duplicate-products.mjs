// Pure detection only. Consolidation is performed by a Gestor-only, revision-checked
// database RPC so invoice reversals and movement references remain consistent.
const fold = (value) => String(value ?? '').normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '').toLowerCase().trim();

export function normalizeProductCode(value) {
  const code = fold(value).toUpperCase().replace(/\s+/g, '');
  if (!code) return '';
  if (/^\d+$/.test(code)) return code.replace(/^0+(?=\d)/, '');
  // Preserve alphabetic prefixes; only normalize padding of a final numeric part.
  return code.replace(/^(.*?[^\d])0+(\d+)$/, (_, prefix, number) =>
    prefix + number.replace(/^0+(?=\d)/, ''));
}

const aliases = { int: 'integral', integ: 'integral', und: 'un', unidade: 'un',
  unidades: 'un', lt: 'l', litro: 'l', litros: 'l', gr: 'g', kgs: 'kg',
  acucar: 'acucar', graos: 'grao', grao: 'grao', pct: 'pacote' };
const stop = new Set(['de', 'do', 'da', 'dos', 'das', 'em', 'para', 'com', 'tipo']);
export function normalizeProductDescription(value) {
  const str = fold(value).replace(/(\d)([a-z])/g, '$1 $2')
    .replace(/([a-z])(\d)/g, '$1 $2').replace(/[^a-z0-9]+/g, ' ');
  return str.split(/\s+/).filter(Boolean).map((part) => aliases[part] || part)
    .filter((part) => !stop.has(part)).join(' ');
}

function normalizedUnit(unit) {
  const value = fold(unit || 'un');
  return ({ unidade: 'un', und: 'un', in: 'un', pc: 'un', lt: 'l', litro: 'l',
    litros: 'l', kgs: 'kg', gr: 'g', caixa: 'cx', pacote: 'pct',
    fardo: 'fd' })[value] || value;
}

function codeSources(product) {
  const sources = [];
  // Autogenerated PRD-xxxxx values are not trustworthy product identifiers.
  if (product?.sku && !/^PRD-\d{5}(?:-\d+)?$/i.test(String(product.sku))) {
    const code = normalizeProductCode(product.sku);
    if (code) sources.push({ code, origin: 'sku', issuer: '' });
  }
  for (const alternative of product?.alternateSkus || []) {
    const code = normalizeProductCode(alternative);
    if (code) sources.push({ code, origin: 'sku', issuer: '' });
  }
  for (const alias of product?.supplierCodes || []) {
    const code = normalizeProductCode(alias?.code);
    const issuer = String(alias?.cnpj || '').replace(/\D/g, '');
    if (code && issuer) sources.push({ code, origin: 'supplier', issuer });
  }
  return sources;
}

function comparable(a, b) {
  // The same number issued by two different suppliers is not proof of identity.
  return !(a.origin === 'supplier' && b.origin === 'supplier' && a.issuer !== b.issuer);
}

function distance(a, b) {
  if (a === b) return 0;
  const rows = [Array.from({ length: b.length + 1 }, (_, i) => i)];
  for (let i = 1; i <= a.length; i++) {
    const next = [i];
    for (let j = 1; j <= b.length; j++) next[j] = Math.min(
      next[j - 1] + 1, rows[i - 1][j] + 1,
      rows[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    rows.push(next);
  }
  return rows[a.length][b.length];
}

function nearCodes(a, b) {
  if (a.length < 4 || b.length < 4 || Math.abs(a.length - b.length) > 1) return false;
  if (distance(a, b) === 1) return true;
  if (a.length !== b.length) return false;
  for (let i = 0; i < a.length - 1; i++) {
    if (a[i] !== b[i]) {
      return a[i] === b[i + 1] && a[i + 1] === b[i] &&
        a.slice(0, i) === b.slice(0, i) && a.slice(i + 2) === b.slice(i + 2);
    }
  }
  return false;
}

export function productNameSimilarity(a, b) {
  const left = normalizeProductDescription(a);
  const right = normalizeProductDescription(b);
  if (!left || !right) return 0;
  if (left === right) return 1;
  const aTokens = new Set(left.split(' '));
  const bTokens = new Set(right.split(' '));
  const common = [...aTokens].filter((token) => bTokens.has(token)).length;
  const jaccard = common / new Set([...aTokens, ...bTokens]).size;
  const sortedA = [...aTokens].sort().join(' ');
  const sortedB = [...bTokens].sort().join(' ');
  const edit = 1 - distance(sortedA, sortedB) / Math.max(sortedA.length, sortedB.length);
  return Math.max(jaccard, edit);
}

function conflictingNumbers(a, b) {
  const numbers = (value) => [...new Set(normalizeProductDescription(value).split(' ')
    .filter((token) => /^\d+(?:[.,]\d+)?$/.test(token)))].sort().join('|');
  const left = numbers(a);
  const right = numbers(b);
  return Boolean(left && right && left !== right);
}

export function checkDuplicatePair(left, right) {
  if (!left || !right || left.id === right.id) return null;
  const similarity = productNameSimilarity(left.name, right.name);
  const sameUnit = normalizedUnit(left.unit) === normalizedUnit(right.unit);
  const specsDiffer = conflictingNumbers(left.name, right.name);
  const leftCodes = codeSources(left);
  const rightCodes = codeSources(right);
  const exact = leftCodes.some((a) => rightCodes.some((b) =>
    comparable(a, b) && a.code === b.code));
  const near = !exact && leftCodes.some((a) => rightCodes.some((b) =>
    comparable(a, b) && nearCodes(a.code, b.code)));
  // Require both signals for typos in codes. Identical descriptions are also
  // interesting even where a supplier uses totally unrelated product codes.
  if (!exact && !(near && similarity >= 0.8) && similarity < 0.86) return null;
  if (specsDiffer && !exact) return null;
  const high = exact && similarity >= 0.82 && sameUnit && !specsDiffer;
  const reasons = [];
  if (exact) reasons.push('Código equivalente (incluindo zeros à esquerda)');
  else if (near) reasons.push('Código com possível erro de digitação');
  if (similarity >= 0.86) reasons.push('Descrição igual ou muito semelhante');
  else if (exact && similarity < 0.48)
    reasons.push('Descrição divergente ou OCR ilegível: verificar o produto no documento original');
  else if (exact) reasons.push('Descrição parcialmente semelhante');
  if (!sameUnit) reasons.push('Unidades diferentes: conferir conversão');
  if (specsDiffer) reasons.push('Números/embalagens diferentes: conferir');
  return {
    left, right, confidence: high ? 'alta' : 'revisar',
    similarity: Math.round(similarity * 100), sameUnit, reasons,
    matchedByCode: exact || near
  };
}

// Apply one ranking to catalog audits and single-product suggestions.
function compareDuplicateConfidence(a, b) {
  return Number(b.confidence === 'alta') - Number(a.confidence === 'alta') ||
    b.similarity - a.similarity;
}

export function findPotentialDuplicates(products) {
  const items = (products || []).filter((p) => p && p.id != null);
  const groups = new Map();
  const pairKeys = new Set();
  const pairs = [];
  for (let i = 0; i < items.length; i++) {
    const product = items[i];
    const name = normalizeProductDescription(product.name);
    const keys = new Set();
    if (name) {
      keys.add('description:' + name);
      for (const token of name.split(' ')) {
        if (token.length >= 4) keys.add('word:' + token.slice(0, 4));
      }
    }
    for (const code of codeSources(product)) {
      keys.add('code:' + (code.origin === 'supplier' ? code.issuer : 'sku') + ':' + code.code);
      // Index globally too: an item's original SKU may only appear later as a
      // supplier alias, or vice versa. checkDuplicatePair checks issuer scope.
      keys.add('normalized-code:' + code.code);
    }
    for (const key of keys) {
      for (const index of groups.get(key) || []) {
        const pairKey = index + ':' + i;
        if (pairKeys.has(pairKey)) continue;
        pairKeys.add(pairKey);
        const match = checkDuplicatePair(items[index], product);
        if (match) pairs.push(match);
      }
      if (!groups.has(key)) groups.set(key, []);
      groups.get(key).push(i);
    }
  }
  return pairs.sort(compareDuplicateConfidence);
}

export function findDuplicatesForCandidate(candidate, products) {
  return (products || []).map((item) => checkDuplicatePair(item, candidate))
    .filter(Boolean).sort(compareDuplicateConfidence);
}
