'use strict';
// Baseline sources are exclusively immutable, versioned historical db/*.sql.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const sources = ['db/schema.sql', 'db/access-permissions.sql', 'db/pending-receipts.sql', 'db/cash-closing.sql'];
const sourceCommit = '93b444e8dea5c6dd17db713003b5349506df41cd';
const target = path.join(root, 'supabase/migrations/20261019000000_legacy_baseline.sql');
let output = '-- Generated by node scripts/build-sql-baseline.cjs; do not edit manually.\n';
output += '-- Historical bootstrap for EMPTY databases only; never replay on an existing project.\n';
output += '-- No production dump, accounts, credentials or remote database are inputs.\n\n';
output += `-- Immutable source commit: ${sourceCommit}\n\n`;
for (const source of sources) {
  const sql = execFileSync('git', ['show', `${sourceCommit}:${source}`],
    { cwd: root, encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 }).replace(/\r\n/g, '\n');
  const digest = createHash('sha256').update(sql).digest('hex');
  output += `-- Source: ${source}; normalized SHA256: ${digest}\n${sql.trimEnd()}\n\n`;
}
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) {
    throw new Error('Baseline differs from immutable historical db/*.sql. Regenerate and review the diff.');
  }
  console.log(`PASS baseline matches the four bootstrap sources at ${sourceCommit}`);
} else {
  fs.writeFileSync(target, output);
  console.log(path.relative(root, target));
}
